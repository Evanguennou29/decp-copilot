"""Evaluation runner: recall@k, MRR and latency over eval/questions.jsonl.

Compares the hybrid pipeline (decp.retrieval.search.search) against a
semantic-only baseline (decp.retrieval.search.semantic_search) to put a
number on the architecture choice made in SPEC.md section 2 (SPEC.md
section 6, lot 4). Not part of CI (SPEC.md section 7): run by hand with
`make eval` or `python eval/run.py`; its output overwrites eval/results.md,
dated, so the numbers there are always from a real run, not hand-edited.
"""

from __future__ import annotations

import json
import statistics
import time
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from decp.config import load_settings
from decp.index.embed import load_encoder
from decp.index.store import load_index
from decp.retrieval.search import TOP_K, search, semantic_search

QUESTIONS_PATH = Path(__file__).parent / "questions.jsonl"
RESULTS_PATH = Path(__file__).parent / "results.md"


@dataclass(frozen=True)
class Question:
    id: str
    question: str
    expected_uids: list[str]
    category: str


def load_questions(path: Path = QUESTIONS_PATH) -> list[Question]:
    questions = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        data = json.loads(line)
        questions.append(
            Question(
                id=data["id"],
                question=data["question"],
                expected_uids=data["expected_uids"],
                category=data["category"],
            )
        )
    return questions


def reciprocal_rank(ranked_ids: list[str], expected_uids: set[str]) -> float:
    for rank, uid in enumerate(ranked_ids, start=1):
        if uid in expected_uids:
            return 1.0 / rank
    return 0.0


def recall_at_k(ranked_ids: list[str], expected_uids: set[str], k: int) -> float:
    if not expected_uids:
        return 0.0
    found = sum(1 for uid in expected_uids if uid in ranked_ids[:k])
    return found / len(expected_uids)


@dataclass(frozen=True)
class ConfigResult:
    name: str
    num_questions: int
    recall_at_k: float
    mrr: float
    mean_latency_ms: float
    p95_latency_ms: float


def _percentile(sorted_values: list[float], pct: float) -> float:
    if not sorted_values:
        return 0.0
    index = min(len(sorted_values) - 1, max(0, round(pct * (len(sorted_values) - 1))))
    return sorted_values[index]


def evaluate_config(
    name: str,
    questions: list[Question],
    run_query: Callable[[Question], list[str]],
    *,
    k: int,
) -> ConfigResult:
    recalls = []
    mrrs = []
    latencies_ms = []
    for q in questions:
        start = time.perf_counter()
        ranked_ids = run_query(q)
        latencies_ms.append((time.perf_counter() - start) * 1000)
        expected = set(q.expected_uids)
        recalls.append(recall_at_k(ranked_ids, expected, k))
        mrrs.append(reciprocal_rank(ranked_ids, expected))

    return ConfigResult(
        name=name,
        num_questions=len(questions),
        recall_at_k=statistics.mean(recalls) if recalls else 0.0,
        mrr=statistics.mean(mrrs) if mrrs else 0.0,
        mean_latency_ms=statistics.mean(latencies_ms) if latencies_ms else 0.0,
        p95_latency_ms=_percentile(sorted(latencies_ms), 0.95),
    )


def _format_row(result: ConfigResult, k: int) -> str:
    return (
        f"| {result.name} | {result.num_questions} | {result.recall_at_k:.2f} "
        f"| {result.mrr:.2f} | {result.mean_latency_ms:.1f} | {result.p95_latency_ms:.1f} |"
    )


def build_report(
    timestamp: str,
    k: int,
    overall: dict[str, ConfigResult],
    by_category: dict[str, dict[str, ConfigResult]],
) -> str:
    header = (
        f"| Configuration | Questions | Recall@{k} | MRR | Mean latency (ms) | p95 latency (ms) |"
    )
    separator = "|---|---|---|---|---|---|"
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `make eval` (`python eval/run.py`) on {timestamp}, "
        f"against `eval/questions.jsonl` ({next(iter(overall.values())).num_questions} "
        "hand-built questions) and the vector index currently on disk "
        "(see README.md, \"Indexed corpus scope\", for what that covers).",
        "",
        f"recall@{k}: fraction of a question's expected market(s) found in the "
        f"top {k} results (1.0 = always found). MRR: mean reciprocal rank of the "
        "first expected match (1.0 = always ranked first, 0 = never found). "
        "Latency is the search call's wall time.",
        "",
        "## Overall",
        "",
        header,
        separator,
    ]
    for result in overall.values():
        lines.append(_format_row(result, k))

    lines += ["", "## By question category", ""]
    for category in sorted(by_category):
        lines.append(f"### {category}")
        lines.append("")
        lines.append(header)
        lines.append(separator)
        for result in by_category[category].values():
            lines.append(_format_row(result, k))
        lines.append("")

    lines += [
        "## Methodology",
        "",
        "- Questions are hand-written from real markets in the currently indexed "
        "corpus (see `scripts/verify_eval_questions.py`, run against every "
        "question before it was added here): each question's `expected_uids` "
        "was checked against `data/decp.duckdb` directly, and the question text "
        "paraphrases the market's content rather than reusing its `objet` "
        "field verbatim, to avoid a circular, self-inflating evaluation.",
        "- **structured**: montant/département/type only, no distinctive content "
        "words — measures pure filter narrowing.",
        "- **semantic**: a content description with no montant/département/date/CPV "
        "filter that would parse — measures embedding/BM25 quality alone.",
        "- **mixed**: both a real filter and distinctive content — the realistic "
        "case for most PME queries.",
        "- **hybrid**: `decp.retrieval.search.search` — structured filters (on the "
        "full lot 1 corpus) + BM25 + semantic, fused by reciprocal rank.",
        "- **semantic-only**: `decp.retrieval.search.semantic_search` — cosine "
        "similarity alone, over the same indexed corpus, no filters, no BM25 — "
        "the baseline the architecture in SPEC.md section 2 argues against.",
        "- Reproduce with `make eval` (needs `python -m decp ingest` and "
        "`python -m decp index` to have been run first).",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    settings = load_settings()
    questions = load_questions()
    encoder = load_encoder()
    vector_index = load_index(settings.vector_index_path)
    k = TOP_K

    def run_hybrid(q: Question) -> list[str]:
        results = search(
            q.question,
            database_path=settings.database_path,
            vector_index=vector_index,
            encoder=encoder,
            top_k=k,
        )
        return [r.uid for r in results]

    def run_semantic(q: Question) -> list[str]:
        return semantic_search(q.question, vector_index=vector_index, encoder=encoder, top_k=k)

    configs: list[tuple[str, Callable[[Question], list[str]]]] = [
        ("hybrid", run_hybrid),
        ("semantic-only", run_semantic),
    ]

    overall = {name: evaluate_config(name, questions, run, k=k) for name, run in configs}

    by_category: dict[str, dict[str, ConfigResult]] = {}
    for category in sorted({q.category for q in questions}):
        subset = [q for q in questions if q.category == category]
        by_category[category] = {
            name: evaluate_config(name, subset, run, k=k) for name, run in configs
        }

    timestamp = datetime.now(UTC).strftime("%Y-%m-%d")
    report = build_report(timestamp, k, overall, by_category)
    RESULTS_PATH.write_text(report, encoding="utf-8")
    print(report)
    print(f"Wrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
